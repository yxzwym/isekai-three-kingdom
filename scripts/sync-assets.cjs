const fs=require('node:fs');const path=require('node:path');
const root=path.resolve(__dirname,'..');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'assets/characters/manifest.json'),'utf8'));
for(const [id,character]of Object.entries(manifest.characters)){
  if(!character.variants[character.defaultVariant])throw new Error(`默认形象不存在：${id}`);
  for(const [variant,art]of Object.entries(character.variants))for(const role of ['portrait','fullbody']){
    const asset=art[role];if(!asset||asset.status==='pending-generation')continue;
    if(!asset.src?.startsWith('./assets/'))throw new Error(`素材路径应位于assets：${id}/${variant}/${role}`);
    const file=path.resolve(root,asset.src);if(!file.startsWith(root+path.sep)||!fs.existsSync(file))throw new Error(`素材缺失：${asset.src}`);
  }
}
fs.writeFileSync(path.join(root,'assets/characters/manifest.js'),`// Generated from manifest.json; do not edit this file.\nglobalThis.CharacterAssetManifest=${JSON.stringify(manifest)};\n`);
module.exports=manifest;
